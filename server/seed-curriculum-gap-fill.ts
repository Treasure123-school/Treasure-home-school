// Helper: standard 3-term topic builder
// t1 = first-term topics (12), t2 = second-term topics (12), t3 = third-term topics (8)
// ─────────────────────────────────────────────────────────────────────────────
function terms(
  t1: string[], t2: string[], t3: string[]
): TopicDef[] {
  const out: TopicDef[] = [];
  t1.forEach((n, i) => out.push({ term: "first",  week: i + 1, name: n }));
  t2.forEach((n, i) => out.push({ term: "second", week: i + 1, name: n }));
  t3.forEach((n, i) => out.push({ term: "third",  week: i + 1, name: n }));
  return out;
}

