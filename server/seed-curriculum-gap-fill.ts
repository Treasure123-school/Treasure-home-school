// ─────────────────────────────────────────────────────────────────────────────
// Seed function — inserts only missing (className × subjectName) pairs
// ─────────────────────────────────────────────────────────────────────────────
export async function seedCurriculumGapFill(): Promise<{
  added: number;
  topicsAdded: number;
  skipped: number;
  report: string[];
}> {
  console.log("📚 Running Nigerian Curriculum Gap-Fill...");

  // Load existing templates to build dedup map
  const existing = await db.select().from(curriculumTemplates);
  const existingSet = new Set(
    existing.map((t) => `${t.className}||${t.subjectName}`)
  );

  const existingList = existing.map((t) => `${t.className} — ${t.subjectName}`);
  const report: string[] = [];
  let added = 0;
  let topicsAdded = 0;
  let skipped = 0;

  report.push(`=== EXISTING TEMPLATES (${existing.length}) ===`);
  existingList.sort().forEach((e) => report.push(`  ✅ ${e}`));

  report.push(`\n=== GAP ANALYSIS ===`);

  const toAdd: TemplateDef[] = [];
  const alreadyHave: string[] = [];
  const willAdd: string[] = [];

  for (const tpl of T) {
    const key = `${tpl.className}||${tpl.subjectName}`;
    if (existingSet.has(key)) {
      alreadyHave.push(`${tpl.className} — ${tpl.subjectName}`);
      skipped++;
    } else {
      willAdd.push(`${tpl.className} — ${tpl.subjectName}`);
      toAdd.push(tpl);
    }
  }

  report.push(`\nSubjects already present (${alreadyHave.length}):`);
  alreadyHave.sort().forEach((s) => report.push(`  ✅ ${s}`));

  report.push(`\nMissing subjects to be added (${willAdd.length}):`);
  willAdd.sort().forEach((s) => report.push(`  ➕ ${s}`));

  // Insert missing templates
  for (const tpl of toAdd) {
    try {
      const [inserted] = await db
        .insert(curriculumTemplates)
        .values({
          title: tpl.title,
          level: tpl.level,
          className: tpl.className,
          subjectName: tpl.subjectName,
          description: tpl.description,
          isPublished: true,
        })
        .returning();

      if (tpl.topics.length > 0) {
        const rows = tpl.topics.map((t, i) => ({
          templateId: inserted.id,
          term: t.term,
          weekNumber: t.week,
          orderNumber: i,
          name: t.name,
          description: t.description ?? null,
        }));
        await db.insert(curriculumTemplateTopics).values(rows);
        topicsAdded += rows.length;
      }
      added++;
    } catch (err: any) {
      report.push(`  ❌ ERROR inserting ${tpl.title}: ${err?.message}`);
    }
  }

  report.push(`\n=== RESULT ===`);
  report.push(`  Templates added: ${added}`);
  report.push(`  Topics added:    ${topicsAdded}`);
  report.push(`  Skipped (exist): ${skipped}`);
  report.push(`  Total now:       ${existing.length + added}`);

  console.log(`✅ Gap fill complete: ${added} templates, ${topicsAdded} topics added.`);
  return { added, topicsAdded, skipped, report };
}
